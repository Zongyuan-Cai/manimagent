"""Readable memory mirrors with explicit, version-checked edits.

SQLite owns committed memory. The manifest records generated bytes so refresh
can preserve detected editor changes until they are explicitly imported.
"""

from __future__ import annotations

import hashlib
import json
import logging
import re
import threading
from functools import wraps
from pathlib import Path

from manimagent.errors import ContentError
from manimagent.storage import write_json, write_text

from .database import fingerprint
from .models import MemoryEntry

MAX_DOCUMENT_BYTES = 512 * 1024
FORMAT = "manimagent-memory-v1"
_DOCUMENT_LOCK = threading.RLock()
_VALUE_MARKER = "\n\n## 记忆内容\n\n"
_EVIDENCE_MARKER = "\n\n<!-- memory-evidence:read-only -->\n"
log = logging.getLogger(__name__)


def document_hash(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def entry_hash(entry: MemoryEntry) -> str:
    return fingerprint(entry.model_dump(mode="json"))


def document_parts(entry: MemoryEntry) -> tuple[str, str]:
    metadata = {
        "format": FORMAT,
        "memory_id": entry.memory_id,
        "base_hash": entry_hash(entry),
        **entry.model_dump(exclude={"memory_id", "value", "evidence"}),
    }
    prefix = "---\n" + json.dumps(metadata, ensure_ascii=False, indent=2) + "\n---" + _VALUE_MARKER
    evidence = json.dumps(
        [item.model_dump() for item in entry.evidence], ensure_ascii=False, indent=2
    )
    # A fence longer than any user-supplied backtick run keeps quotes inert in Markdown.
    fence = "`" * max(3, max((len(run) + 1 for run in re.findall(r"`+", evidence)), default=3))
    suffix = (
        _EVIDENCE_MARKER
        + "## 来源证据（只读）\n\n"
        + fence
        + "json\n"
        + evidence
        + "\n"
        + fence
        + "\n\n仅编辑“记忆内容”，然后显式导入。元数据与证据不能修改；确认沉淀请使用记忆管理操作。\n"
    )
    return prefix, suffix


def render_document(entry: MemoryEntry) -> str:
    prefix, suffix = document_parts(entry)
    return prefix + entry.value + suffix


def _check_size(content: str) -> None:
    try:
        size = len(content.encode("utf-8"))
    except (AttributeError, UnicodeError) as exc:
        raise ContentError("memory_document_invalid", "记忆文件必须是有效 UTF-8 文本", 422) from exc
    if size > MAX_DOCUMENT_BYTES:
        raise ContentError("memory_document_invalid", "记忆文件不能超过 512 KiB", 422)


def parse_edit(content: str, entry: MemoryEntry) -> str:
    _check_size(content)
    # Native editors commonly save CRLF; line endings do not change a memory value.
    content = content.replace("\r\n", "\n")
    try:
        if not content.startswith("---\n"):
            raise ValueError()
        header, _ = content[4:].split("\n---" + _VALUE_MARKER, 1)
        metadata = json.loads(header)
        if not isinstance(metadata, dict) or metadata.get("memory_id") != entry.memory_id:
            raise ValueError()
    except (ValueError, TypeError) as exc:
        raise ContentError(
            "memory_document_invalid", "记忆文件格式无效，请保留原元数据和证据", 422
        ) from exc
    if metadata.get("base_hash") != entry_hash(entry):
        raise ContentError(
            "memory_document_conflict",
            "记忆已变化，草稿已保留；请核对当前记忆并通过纠正处理需要保留的内容",
            409,
        )
    prefix, suffix = document_parts(entry)
    if not content.startswith(prefix) or not content.endswith(suffix):
        raise ContentError(
            "memory_document_invalid", "只允许编辑记忆内容，不能修改元数据或证据", 422
        )
    return content[len(prefix) : -len(suffix)]


def publish_documents(method):
    """Run best-effort mirror publication only after the database transaction closes."""

    @wraps(method)
    def wrapped(self, *args, **kwargs):
        result = method(self, *args, **kwargs)
        self.sync_documents()
        return result

    return wrapped


class MemoryDocuments:
    def __init__(self, store):
        self.store = store
        self.root = store.path.parent.resolve() / "memory"
        self.index_path = self.root / "MEMORY.md"
        self.manifest_path = self.root / ".manifest.json"
        self._accepted: dict[str, str] = {}

    def _guard(self, path: Path) -> Path:
        if self.root.resolve() != self.root or not path.resolve().is_relative_to(self.root):
            raise ContentError("memory_document_invalid", "记忆目录不能指向目录外部", 422)
        current = path
        while current != self.root:
            if current.is_symlink() or current.is_junction():
                raise ContentError("memory_document_invalid", "记忆文件不能使用链接或目录联接", 422)
            current = current.parent
        return path

    def path(self, memory_id: str) -> Path:
        if not isinstance(memory_id, str) or not re.fullmatch(r"memory_[0-9a-f]{32}", memory_id):
            raise ContentError("memory_document_invalid", "记忆文件标识无效", 422)
        return self._guard(self.root / "entries" / (memory_id + ".md"))

    @staticmethod
    def _read(path: Path, limit: int = MAX_DOCUMENT_BYTES) -> str:
        with path.open("rb") as stream:
            data = stream.read(limit + 1)
        if len(data) > limit:
            raise ContentError("memory_document_invalid", "记忆文件大小超过限制", 422)
        try:
            return data.decode("utf-8")
        except UnicodeError as exc:
            raise ContentError("memory_document_invalid", "记忆文件必须是 UTF-8 编码", 422) from exc

    def read(self, memory_id: str) -> str:
        with _DOCUMENT_LOCK:
            try:
                return self._read(self.path(memory_id))
            except FileNotFoundError as exc:
                raise ContentError(
                    "memory_document_not_found", "记忆文件不存在，请刷新文件目录", 404
                ) from exc
            except OSError as exc:
                raise ContentError("memory_document_unavailable", "无法读取记忆文件", 503) from exc

    def _manifest(self) -> dict:
        path = self._guard(self.manifest_path)
        if not path.exists():
            return {}
        try:
            data = json.loads(self._read(path, 5 * 1024 * 1024))
            if data.get("format") != FORMAT or not isinstance(data.get("entries"), dict):
                raise ValueError()
            result = data["entries"]
            for memory_id, item in result.items():
                self.path(memory_id)
                if not isinstance(item, dict) or set(item) != {"generated_hash", "base_hash"}:
                    raise ValueError()
                if any(
                    not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value)
                    for value in item.values()
                ):
                    raise ValueError()
            return result
        except (ValueError, TypeError, AttributeError) as exc:
            raise ContentError(
                "memory_document_invalid", "记忆文件清单损坏，原文件已保留", 422
            ) from exc

    def sync(self) -> dict:
        with _DOCUMENT_LOCK:
            status = {
                "root": str(self.root),
                "index_path": str(self.index_path),
                "index_content": "",
                "entries": [],
                "error": None,
            }
            try:
                self._sync(status)
            except Exception as exc:
                log.warning("记忆文件同步失败，已提交的数据库记忆保持有效", exc_info=True)
                status["error"] = {
                    "code": exc.error.code
                    if isinstance(exc, ContentError)
                    else "memory_document_unavailable",
                    "message": exc.error.message
                    if isinstance(exc, ContentError)
                    else "记忆已保存在数据库，但文件同步失败；请检查目录后刷新重试",
                }
            return status

    def _sync(self, status):
        # A committed import may outlive a transient file lock. Retry its cleanup
        # without deleting a different draft saved by another editor meanwhile.
        for memory_id, accepted_hash in list(self._accepted.items()):
            path = self.path(memory_id)
            if (
                path.exists()
                and document_hash(self._read(path).replace("\r\n", "\n")) == accepted_hash
            ):
                path.unlink()
            del self._accepted[memory_id]
        manifest = self._manifest()
        entries = {entry.memory_id: entry for entry in self.store.list_entries()}
        folder = self._guard(self.root / "entries")
        folder.mkdir(parents=True, exist_ok=True)
        # Only this component's entries directory is scanned; snapshots have a separate owner.
        present = {path.stem for path in folder.glob("memory_*.md")}
        for memory_id in sorted(entries.keys() | manifest.keys() | present):
            path = self.path(memory_id)
            entry = entries.get(memory_id)
            previous = manifest.get(memory_id)
            existing = self._read(path) if path.exists() else None
            unchanged = (
                existing is not None
                and previous is not None
                and document_hash(existing) == previous["generated_hash"]
            )
            if entry is None:
                if existing is None or unchanged:
                    latest = self._read(path) if path.exists() else None
                    if latest == existing:
                        path.unlink(missing_ok=True)
                        manifest.pop(memory_id, None)
                        continue
                state = "deleted"
            else:
                content = render_document(entry)
                base = entry_hash(entry)
                # Rendering a large evidence file takes time. Recheck the file
                # immediately before publication, preserving edits made meanwhile.
                latest = self._read(path) if path.exists() else None
                if latest != existing:
                    existing, unchanged = latest, False
                if existing is None or unchanged:
                    if existing != content:
                        write_text(path, content)
                    manifest[memory_id] = {
                        "generated_hash": document_hash(content),
                        "base_hash": base,
                    }
                    state = "current"
                else:
                    state = "stale" if previous and previous["base_hash"] != base else "edited"
            status["entries"].append(
                {
                    "memory_id": memory_id,
                    "path": str(path),
                    "status": state,
                    "field": entry.field if entry else None,
                    "layer": entry.layer if entry else None,
                }
            )
        manifest_data = {"format": FORMAT, "entries": manifest}
        if (
            not self.manifest_path.exists()
            or json.loads(self._read(self.manifest_path, 5 * 1024 * 1024)) != manifest_data
        ):
            write_json(self.manifest_path, manifest_data)
        lines = [
            "# 用户记忆索引",
            "",
            "SQLite 保存已提交记忆。条目文件可阅读；仅编辑记忆内容，显式导入后生效。",
            "",
            "索引由系统生成。edited 为待导入编辑，stale 为原记忆已变化，deleted 为原记忆已清理但编辑仍保留。",
            "",
        ]
        for item in status["entries"]:
            field = (
                json.dumps(item["field"], ensure_ascii=False)
                if item["field"] is not None
                else "已清理的条目"
            )
            lines.append(
                f"- [{item['memory_id']}](entries/{item['memory_id']}.md) · {field} · {item['layer'] or '—'} · {item['status']}"
            )
        if not status["entries"]:
            lines.append("暂无记忆条目。")
        content = "\n".join(lines) + "\n"
        self._guard(self.index_path)
        if not self.index_path.exists() or self._read(self.index_path, 5 * 1024 * 1024) != content:
            write_text(self.index_path, content)
        status["index_content"] = content

    def accepted(self, memory_id: str, content: str) -> None:
        """Schedule cleanup; publication failures must never hide a committed import."""
        with _DOCUMENT_LOCK:
            self._accepted[memory_id] = document_hash(content.replace("\r\n", "\n"))
